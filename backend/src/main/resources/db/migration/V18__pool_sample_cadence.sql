-- ============================================================
-- V18: 号池明细采集改为 10 分钟增量采集
-- ============================================================
-- 背景：
--   上游 /admin/usage 只支持按天过滤，明细需要本地增量落库后再聚合。
--   15 分钟一轮对 70+ 个号池账号来说粒度偏粗，调整为 10 分钟；
--   采集本身是增量的（按 last_sample_at 水位 + request_id 去重），
--   首次最多回溯 7 天，之后每轮只补最近增量，避免长时间卡顿。

UPDATE scheduled_tasks
SET cron_expression = '0 */10 * * * ?',
    description    = '增量采集号池逐请求明细（缓存命中率、首 token 耗时等），每 10 分钟一轮',
    updated_at     = now()
WHERE task_code = 'pool-samples';