-- ============================================================
-- V20: 号池明细「往回补齐」游标
-- ============================================================
-- 背景：
--   上游 /admin/usage 只支持按天过滤，单账号单轮最多翻 N 页（每页 1000 条）。
--   首次接入（回溯 7 天）、服务停机后补数、或某账号流量暴涨时，单次窗口的行数
--   可能超过翻页上限。此时只会取到「最新」的一段，而旧实现仍把水位推进到最新一条，
--   导致中间缺口永远不会再取（实测已丢失 1811 条）。
--
-- 方案：
--   新增 backfill_until 作为「往回补齐」游标。一旦某轮触顶：
--     - 不推进 last_sample_at（水位）；
--     - 把 backfill_until 设为本次取到的最早一条时间；
--     - 下一轮用 end_date = backfill_until 继续往更早的方向取，直到补齐到目标起点，
--       再把 backfill_until 清空、恢复正常的增量推进。

ALTER TABLE pool_accounts
    ADD COLUMN backfill_until TIMESTAMPTZ;

COMMENT ON COLUMN pool_accounts.backfill_until IS
    '明细往回补齐游标：非空表示还有比该时间更早的缺口未取，下一轮以此为查询上界继续回补';